/**
 * Feedback rounds from the command line (the justfile recipes call this; run from the repo root).
 *
 *   bun scripts/review/cli.ts round open <name> [--feed] [--no-rotate] [--changed [--since <round>]] [icon ...]
 *     --changed: only icons whose renders changed since the last round (or --since <round>), by content hash
 *   bun scripts/review/cli.ts round close <name> [--feed | --no-feed]
 *   bun scripts/review/cli.ts round list
 *   bun scripts/review/cli.ts feedback [round]
 *   bun scripts/review/cli.ts share [round]
 *   bun scripts/review/cli.ts rotate
 *
 * The share link's secrets (REVIEW_USER, REVIEW_PASSWORD, REVIEW_SLUG) live in the gallery's .env,
 * generated by via from tools/icon-gallery/tpl.env with getRandomString macros. Rotating removes the two
 * random ones and lets `via env init` draw new ones. Only `share` ever prints the password.
 */
import { chmod, readFile, rename, stat } from "node:fs/promises"
import { join, resolve } from "node:path"
import { readFeedbackForGeneration, writeFeedback } from "./feedback"
import { snapshot } from "./snapshot"
import { repoStore } from "./store"
import { ROUND_NAME } from "./types"

const ROOT = resolve(import.meta.dir, "../..")
const GALLERY = resolve(process.env.REVIEW_GALLERY_DIR ?? join(ROOT, "tools/icon-gallery"))
const ENV_FILE = join(GALLERY, ".env")
const FEEDBACK_DIR = repoStore(ROOT).feedbackDir
const LOCAL_URL = `http://127.0.0.1:${process.env.ICON_GALLERY_PORT ?? 5330}`
export const reviewStore = () => repoStore(ROOT).store

/** KEY=value pairs of a .env file (quotes stripped), without ever printing them. */
export async function readEnv(file = ENV_FILE): Promise<Record<string, string>> {
  const text = await readFile(file, "utf8").catch(() => "")
  const out: Record<string, string> = {}
  for (const l of text.split("\n")) {
    const m = l.match(/^\s*([A-Za-z_]\w*)\s*=\s*(.*)$/)
    if (m) out[m[1]] = m[2].trim().replace(/^(["'])(.*)\1$/, "$2")
  }
  return out
}

const ROTATED = ["REVIEW_PASSWORD", "REVIEW_SLUG"]

/**
 * New random slug and password: drop just those two lines from the gallery's .env (every other line
 * stays byte for byte) and let `via env init` fill them again from tpl.env's macros.
 */
async function rotate() {
  const exists = await stat(ENV_FILE).then(
    () => true,
    () => false,
  )
  if (exists) {
    const text = await readFile(ENV_FILE, "utf8")
    const kept = text
      .split("\n")
      .filter((l) => !ROTATED.some((k) => new RegExp(`^\\s*${k}\\s*=`).test(l)))
      .join("\n")
    const tmp = `${ENV_FILE}.rotate.tmp`
    await Bun.write(tmp, kept)
    const mode = (await stat(ENV_FILE)).mode & 0o777
    await chmod(tmp, mode)
    await rename(tmp, ENV_FILE)
  }
  await envInit()
  const env = await readEnv()
  if (!env.REVIEW_SLUG || !env.REVIEW_PASSWORD)
    throw new Error("via env init did not set REVIEW_SLUG / REVIEW_PASSWORD")
  console.log("rotated the share link: new slug and password (run `just review-share` to see the link)")
}

/** `via env init` in the gallery directory: adds missing keys from tpl.env, keeps existing values. */
async function envInit() {
  const p = Bun.spawnSync(["via", "env", "init"], { cwd: GALLERY, stdout: "pipe", stderr: "pipe" })
  if (p.exitCode !== 0) throw new Error(`via env init failed in ${GALLERY}: ${p.stderr.toString().slice(0, 400)}`)
}

/** The gallery's public tunnel URL from `via urls --json`, if a Relay published it. */
function publicOrigin(): string | null {
  const p = Bun.spawnSync(["via", "urls", "--json"], { cwd: GALLERY, stdout: "pipe", stderr: "pipe" })
  if (p.exitCode !== 0) return null
  try {
    const rows = JSON.parse(p.stdout.toString()) as { id?: string; direct_url?: string; tunnel_url?: string | null }[]
    const row = rows.find((r) => r.tunnel_url && (r.id === "gallery" || /:(5330)\b/.test(r.direct_url ?? "")))
    return row?.tunnel_url ? new URL(row.tunnel_url).origin : null
  } catch {
    return null
  }
}

async function share(roundArg?: string) {
  const store = reviewStore()
  const round = roundArg ?? (await store.current())?.name
  if (!round) throw new Error("no round yet: just review-round open <name>")
  const env = await readEnv()
  const user = env.REVIEW_USER
  const pass = env.REVIEW_PASSWORD
  const slug = env.REVIEW_SLUG
  const path = `/approve?round=${encodeURIComponent(round)}`
  console.log(`Round ${round}\n`)
  console.log(`Local (this machine, owner, no login): ${LOCAL_URL}${path}\n`)
  if (!user || !pass || !slug) {
    console.log("No share secrets yet: run `just review-round open <name>` (or `just review-rotate`) first.")
    return
  }
  const origin = publicOrigin()
  const host = origin ? new URL(origin).host : "<public host>"
  const full = `/r/${slug}${path}`
  console.log("Share this link (login included):")
  console.log(`  https://${encodeURIComponent(user)}:${encodeURIComponent(pass)}@${host}${full}\n`)
  console.log("If a browser drops the login from the link, share these instead:")
  console.log(`  URL:      https://${host}${full}`)
  console.log(`  User:     ${user}`)
  console.log(`  Password: ${pass}`)
  if (!origin)
    console.log(
      "\nNo public address found (`via urls` shows no tunnel for the gallery). Start it with `just icons-gallery`\n" +
        "and a Viaalink Relay (`via relay list`); the host is icons-<slug>.<your relay domain>.",
    )
}

/** sha256 of every render a round shows (key → hash), so a later round can show only what changed. */
async function renderHashes(roundsDir: string, snap: Awaited<ReturnType<typeof snapshot>>) {
  const out: Record<string, string> = {}
  for (const icon of snap)
    for (const [style, modes] of Object.entries(icon.images))
      for (const key of Object.values(modes ?? {})) {
        const rel = key.replace(/^round:/, "")
        const file = join(roundsDir, `${rel}.${style === "flat" ? "svg" : "png"}`)
        const buf = await Bun.file(file)
          .arrayBuffer()
          .catch(() => null)
        if (buf) out[key] = new Bun.CryptoHasher("sha256").update(buf).digest("hex")
      }
  return out
}
const hashFile = (dir: string, round: string) => join(dir, `${round}.hashes.json`)
async function writeHashes(dir: string, round: string, h: Record<string, string>) {
  await Bun.write(hashFile(dir, round), JSON.stringify(h))
}
async function readHashes(dir: string, round: string): Promise<Record<string, string>> {
  const f = Bun.file(hashFile(dir, round))
  if (!(await f.exists())) throw new Error(`round ${round} has no render hashes`)
  return f.json()
}
/** The newest other round that recorded render hashes. */
async function lastHashedRound(dir: string, except: string) {
  const { readdir, stat } = await import("node:fs/promises")
  const files = (await readdir(dir).catch(() => [] as string[])).filter((f) => f.endsWith(".hashes.json"))
  const rounds = files.map((f) => f.slice(0, -".hashes.json".length)).filter((r) => r !== except)
  const timed = await Promise.all(rounds.map(async (r) => ({ r, t: (await stat(hashFile(dir, r))).mtimeMs })))
  return timed.sort((a, b) => b.t - a.t)[0]?.r
}

async function main() {
  const [cmd, sub, ...rest] = process.argv.slice(2)
  const si = rest.indexOf("--since")
  const sinceArg = si >= 0 ? rest[si + 1] : undefined
  if (si >= 0) rest.splice(si, 2)
  const flags = new Set(rest.filter((a) => a.startsWith("--")))
  const names = rest.filter((a) => !a.startsWith("--"))
  const store = reviewStore()
  if (cmd === "round" && sub === "list") {
    for (const r of await store.list())
      console.log(
        `${r.name}\t${r.status}\t${r.feed ? "feeds" : "closed circle"}\t${r.icons.length} icons\t${r.createdAt}`,
      )
    return
  }
  if (cmd === "round" && (sub === "open" || sub === "close")) {
    const [name, ...icons] = names
    if (!name || !ROUND_NAME.test(name)) throw new Error("round name: letters, digits, dot, dash, underscore")
    if (sub === "open") {
      const roundsDir = join(ROOT, "local/icons/rounds")
      let snap = await snapshot(roundsDir, icons)
      const hashes = await renderHashes(roundsDir, snap)
      if (flags.has("--changed")) {
        const since = sinceArg ?? (await lastHashedRound(store.roundsDir, name))
        if (!since) throw new Error("--changed: no earlier round with render hashes; open a full round first")
        const before = await readHashes(store.roundsDir, since)
        snap = snap.filter((icon) =>
          Object.values(icon.images).some((m) => Object.values(m ?? {}).some((k) => hashes[k] !== before[k])),
        )
        console.log(`--changed since ${since}: ${snap.length} icons changed`)
        if (!snap.length) return console.log("nothing changed: no round opened")
      }
      const r = await store.open(name, snap, flags.has("--feed"))
      await writeHashes(store.roundsDir, name, hashes)
      console.log(
        `round ${r.name} open: ${r.icons.length} icons, ${r.feed ? "feeds the next generation run" : "closed circle (not fed unless closed with --feed)"}`,
      )
      if (!flags.has("--no-rotate")) await rotate()
      else if (!(await readEnv()).REVIEW_SLUG) await envInit()
      return
    }
    const r = await store.get(name)
    let feed = flags.has("--feed") ? true : flags.has("--no-feed") ? false : r.feed
    if (!flags.has("--feed") && !flags.has("--no-feed") && process.stdin.isTTY) {
      const a = prompt(`Feed round ${name} into the next generation run? [${r.feed ? "Y/n" : "y/N"}]`)
        ?.trim()
        .toLowerCase()
      if (a) feed = a.startsWith("y")
    }
    await store.close(name, feed)
    const out = await writeFeedback(await store.get(name), FEEDBACK_DIR)
    console.log(`round ${name} closed (${feed ? "fed into the next run" : "closed circle, archived, not fed"})`)
    console.log(`feedback: ${out.json}\nsummary:  ${out.md}`)
    return
  }
  if (cmd === "feedback") {
    const r = sub ? await store.get(sub) : await store.current()
    if (!r) throw new Error("no round yet")
    const out = await writeFeedback(r, FEEDBACK_DIR)
    const f = out.file
    console.log(
      `${r.name}: ${f.regenerate.length} to regenerate, ${f.buildInBlender.length} to build in Blender, ${f.newIcons.length} new icon requests, ${f.feed ? "feeds" : "closed circle (not fed)"}`,
    )
    console.log(`feedback: ${out.json}\nsummary:  ${out.md}`)
    if (f.feed) for (const style of ["25d", "flat"]) await readFeedbackForGeneration(out.json, style)
    return
  }
  if (cmd === "share") return share(sub)
  if (cmd === "rotate") return rotate()
  throw new Error("usage: cli.ts round open|close|list <name> | feedback [round] | share [round] | rotate")
}

if (import.meta.main)
  await main().catch((e) => {
    console.error(`review: ${(e as Error).message}`)
    process.exit(1)
  })
